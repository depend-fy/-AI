def render_competition_alignment() -> None:
    """赛题闭环对照：任务规划 / 工具调用 / 执行反馈 / 结果验证 / 异常处理。

    每一行都指向**可当场验证的证据**（检索痕迹、原始留档、规则编号、复核结论），
    而不是只写一句"我们实现了闭环"。
    """
    st.markdown("#### 任务闭环对照")
    st.caption(
        "按赛事要求的五个环节列出实现方式与可验证证据。每项证据都能在系统中当场打开。"
    )
    st.markdown(
        """
| 环节 | 本作品的实现 | 可验证证据 |
| --- | --- | --- |
| **任务规划** | 接收文本后自动规划核验路径：拆分事实主张 → 判定主张类型 → 决定检索策略（DOI 精确查询 / 书目检索 / 预印本检索 / 明确不检索并说明原因） | 每条主张的检索痕迹：查询词、命中数、未检索原因 |
| **工具调用** | 真实调用 Crossref、OpenAlex、arXiv 三个公开学术数据源；带限速、结果缓存与**原始响应留档** | 证据条目中的来源链接与原始响应留档路径；检索统计（查询次数 / 实际请求 / 缓存命中） |
| **执行反馈** | 11 步流水线实时回传阶段进度；每一步的输入输出均为结构化数据 | 工作台的阶段进度与「阶段明细」面板 |
| **结果验证** | 双层验证：确定性规则表裁决（6 种状态 / 8 类问题 / 严重度）＋ 跨厂商独立复核（三项确定性检查 + 两项语义检查） | 每条结论可点开证据；显示命中的规则编号；复核逐项给出通过/未通过与理由 |
| **异常处理** | 区分「服务端明确 404」与「网络失败」；模型调用失败时降级为规则引擎并如实声明；检索失败标注「暂无法核验」；命中缓存时标注数据来源 | 报告中的「数据来源」标注、降级说明、规则 N0、检索失败记录 |
"""
    )
    st.caption(
        "补充说明：本作品**不做**「让模型自己判断有没有错」这件事——"
        "评测数据显示，直接询问模型的误报率为 44.9%（详见评测页三基线对照）。"
    )
