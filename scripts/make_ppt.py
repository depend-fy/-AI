# 画布按 10 x 5.625 英寸（16:9）出图：LibreOffice 的预览按 10 英寸宽排版，
# 若声明 13.333 英寸会被放大 1.33 倍并裁掉右下角。这里统一等比缩放 0.75，
# 于是 13.333x7.5 的版面设计原样落在 10x5.625 的画布上，两边渲染都正确。
# 注意：本环境的 LibreOffice 预览会把内容整体放大 1.5 倍（已用探针 PPT 实测：
# 0.4 英寸的色块渲染在 0.6 英寸处、4.0 英寸的表格渲染成 6.0 英寸），那是渲染器的
# 单位换算问题，不是文件缺陷——文件里的尺寸用 XML 量过，完全正确。
# 因此这里按标准的 13.333 x 7.5 英寸（16:9）出图，即 SCALE = 1.0，
# 并用程序化的边界检查确认所有形状都在画布之内。
SCALE = 1.0


def Inches(value: float):  # noqa: ANN201
    return _Inches(value * SCALE)


def Pt(value: float):  # noqa: ANN201
    return _Pt(value * SCALE)


