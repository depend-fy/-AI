def add_slide() -> object:
    return prs.slides.add_slide(BLANK)


def textbox(slide, x, y, w, h, lines) -> object:  # noqa: ANN001
    """lines: list of (text, size, bold, color, space_after)"""
    box = slide.shapes.add_textbox(Inches(x), Inches(y), Inches(w), Inches(h))
    frame = box.text_frame
    frame.word_wrap = True
    for index, item in enumerate(lines):
        text, size, bold, color = item[0], item[1], item[2], item[3]
        space_after = item[4] if len(item) > 4 else 6
        para = frame.paragraphs[0] if index == 0 else frame.add_paragraph()
        para.space_after = Pt(space_after)
        run = para.add_run()
        run.text = text
        run.font.size = Pt(size)
        run.font.bold = bold
        run.font.color.rgb = color
    return box


def title_bar(slide, title: str, subtitle: str | None = None) -> None:  # noqa: ANN001
    textbox(slide, 0.55, 0.3, 11.5, 0.7, [(title, 28, True, DARK, 0)])
    if subtitle:
        textbox(slide, 0.55, 0.98, 11.5, 0.45, [(subtitle, 13, False, GRAY, 0)])


def table(slide, x, y, w, h, header, rows, col_widths, font_size=12) -> object:  # noqa: ANN001
    shape = slide.shapes.add_table(len(rows) + 1, len(header), Inches(x), Inches(y), Inches(w), Inches(h))
    tbl = shape.table
    for index, width in enumerate(col_widths):
        tbl.columns[index].width = Inches(width)
    for col, name in enumerate(header):
        cell = tbl.cell(0, col)
        cell.text = name
        para = cell.text_frame.paragraphs[0]
        para.runs[0].font.size = Pt(font_size)
        para.runs[0].font.bold = True
        para.runs[0].font.color.rgb = RGBColor(0xFF, 0xFF, 0xFF)
        cell.fill.solid()
        cell.fill.fore_color.rgb = BLUE
    for row_index, row in enumerate(rows, start=1):
        for col, value in enumerate(row):
            cell = tbl.cell(row_index, col)
            cell.text = str(value)
            para = cell.text_frame.paragraphs[0]
            para.runs[0].font.size = Pt(font_size)
            para.runs[0].font.color.rgb = RGBColor(0x22, 0x22, 0x22)
    return tbl


def shot_note(slide, x, y, w, h, text: str) -> None:  # noqa: ANN001
    """截图占位框：明确告诉使用者截哪个页面、要出现什么。"""
    shape = slide.shapes.add_shape(MSO_SHAPE.ROUNDED_RECTANGLE, Inches(x), Inches(y), Inches(w), Inches(h))
    shape.fill.solid()
    shape.fill.fore_color.rgb = RGBColor(0xFF, 0xF6, 0xE5)
    shape.line.color.rgb = RGBColor(0xF2, 0xD0, 0x8A)
    frame = shape.text_frame
    frame.word_wrap = True
    para = frame.paragraphs[0]
    para.alignment = PP_ALIGN.LEFT
    run = para.add_run()
    run.text = text
    run.font.size = Pt(11)
    run.font.color.rgb = RGBColor(0x7A, 0x45, 0x00)


def footer(slide, text: str) -> None:  # noqa: ANN001
    textbox(slide, 0.55, 7.0, 11.5, 0.4, [(text, 10, False, GRAY, 0)])


